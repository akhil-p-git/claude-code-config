#!/usr/bin/env bash
# PreToolUse(Edit|Write|MultiEdit|NotebookEdit): steer edits away from files that must
# not be hand-edited, with a reason Claude can act on.
#   deny: secrets (.env*), lockfiles, .git internals, installed dependencies, credential stores
#   ask:  shell startup/autostart files, build output, files whose header says "generated"
# Complements (does not replace) permission rules: Read/Edit deny rules also cover Bash
# sed/tee/redirects, which this hook never sees. Paths arrive absolute (Claude Code
# expands ~ and relative paths before hooks run). Exits 0 with no output = no opinion.

input="$(cat)"
IFS=$'\x1f' read -r tool fp < <(jq -r '[.tool_name // "", (.tool_input.file_path // .tool_input.notebook_path // "")] | join("\u001f")' <<<"$input" 2>/dev/null)
[ -z "$fp" ] && exit 0
fp="${fp//\\//}"
name="${fp##*/}"
decision=""; reason=""

case "$name" in
  .env|.env.*)
    case "$name" in
      .env.example|.env.sample|.env.template|.env.dist|.env.defaults|.env.schema|.env.*.example) ;;
      *) decision=deny; reason="$name holds real secrets. Do not write it; tell the user which variable to set (and document it in .env.example)" ;;
    esac ;;
  package-lock.json|npm-shrinkwrap.json|pnpm-lock.yaml|yarn.lock|bun.lock|bun.lockb|poetry.lock|uv.lock|Pipfile.lock|Cargo.lock|composer.lock|Gemfile.lock|go.sum|flake.lock|deno.lock)
    decision=deny; reason="$name is generated by the package manager. Change the manifest and run the install/lock command (npm/pnpm/yarn/bun install, uv lock, cargo update, go mod tidy) instead" ;;
esac

if [ -z "$decision" ]; then
  case "$fp" in
    */.git/*) decision=deny; reason="files under .git/ are git's internal state; use git commands" ;;
    */node_modules/*|*/site-packages/*|*/.venv/*|*/venv/lib/*)
      decision=deny; reason="installed dependency code is overwritten on the next install; use patch-package / pnpm patch, or change the dependency" ;;
    "$HOME"/.ssh/*|"$HOME"/.gnupg/*|"$HOME"/.aws/*|"$HOME"/.config/gh/*|"$HOME"/.claude/.credentials.json|"$HOME"/.secrets.env)
      decision=deny; reason="credential store; only the user should change it" ;;
    "$HOME"/.bashrc|"$HOME"/.bash_profile|"$HOME"/.bash_login|"$HOME"/.profile|"$HOME"/.zshrc|"$HOME"/.zprofile|"$HOME"/.zshenv|"$HOME"/.config/fish/config.fish|"$HOME"/.config/autostart/*|"$HOME"/.config/systemd/user/*|"$HOME"/.config/environment.d/*)
      decision=ask; reason="$name runs automatically at login/startup" ;;
    */.next/*|*/.turbo/*|*/__pycache__/*|*/.svelte-kit/*|*/.nuxt/*|*/.output/*|*/.vercel/output/*)
      decision=ask; reason="this is build output that the next build regenerates; edit the source instead" ;;
  esac
fi

# Generated files announce themselves in their first lines (Prisma client, protobuf, codegen, ...).
if [ -z "$decision" ] && [ -f "$fp" ] && head -c 2048 -- "$fp" 2>/dev/null \
     | grep -qiE '@generated|do not edit|code generated .* do not edit|auto-?generated (file|by)|this file (is|was) (auto-?)?generated'; then
  decision=ask; reason="the file header says it is generated; edit its source/schema and regenerate"
fi

[ -z "$decision" ] && exit 0
jq -cn --arg d "$decision" --arg r "protect-files: $reason." \
  '{hookSpecificOutput: {hookEventName: "PreToolUse", permissionDecision: $d, permissionDecisionReason: $r}}'
exit 0
