#!/usr/bin/env bash
# Synthetic PreToolUse(Edit/Write) payloads for protect-files.sh.
here="$(cd "$(dirname "$0")" && pwd)"; hook="$here/../protect-files.sh"
cd "$here/fx" || exit 1
mkdir -p "$here/fx/gen"; gen="$here/fx/gen/schema.generated.ts"; [ -f "$gen" ] || printf '// @generated by prisma-client. DO NOT EDIT.\nexport {}\n' > "$gen"
pass=0; fail=0
t() {  # t <expect> <tool> <path>
  local p out got
  p="$(jq -cn --arg tool "$2" --arg fp "$3" '{session_id:"t",cwd:"/x",hook_event_name:"PreToolUse",tool_name:$tool,tool_input:{file_path:$fp,old_string:"a",new_string:"b"}}')"
  out="$(printf '%s' "$p" | "$hook")"; got="$(jq -r '.hookSpecificOutput.permissionDecision // empty' <<<"$out" 2>/dev/null)"; got="${got:-none}"
  if [ "$got" = "$1" ]; then pass=$((pass+1)); else fail=$((fail+1)); echo "FAIL want=$1 got=$got $2 $3 :: $(jq -r '.hookSpecificOutput.permissionDecisionReason // empty' <<<"$out")"; fi
}
A="$HOME/work/Dev/app"
t deny Edit  "$A/.env"
t deny Write "$A/.env.local"
t deny Edit  "$A/apps/web/.env.production"
t none Edit  "$A/.env.example"
t none Write "$A/.env.local.example"
t deny Edit  "$A/package-lock.json"
t deny Edit  "$A/pnpm-lock.yaml"
t deny Write "$A/uv.lock"
t deny Edit  "$A/.git/config"
t deny Edit  "$A/node_modules/next/dist/server.js"
t deny Edit  "$A/.venv/lib/python3.12/site-packages/x.py"
t deny Write "$HOME/.ssh/config"
t ask  Edit  "$HOME/.bashrc"
t ask  Write "$HOME/.config/systemd/user/backdoor.service"
t ask  Edit  "$A/.next/server/app.js"
t ask  Edit  "$gen"
t none Edit  "$A/src/app/page.tsx"
t none Write "$A/README.md"
t none Edit  "$A/package.json"
t none Edit  "$HOME/dev/claude-code-config/.claude/settings.json"
t none Edit  "$A/src/environment.ts"
echo "protect-files: $pass passed, $fail failed"
